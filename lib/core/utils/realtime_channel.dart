/// Уникальные имена для Supabase Realtime-каналов.
///
/// supabase-flutter кэширует каналы по `topic` (имени). Если два одновременных
/// подписчика открывают канал с ОДИНАКОВЫМ именем, они делят один объект —
/// и `removeChannel` одного (например, при пересоздании BLoC на навигации)
/// срывает подписку другого. Live-обновления при этом молча перестают
/// приходить: ни ошибки, ни краша — данные просто «застывают».
///
/// Для денежно-критичных стримов (балансы, журнал, переводы) это самый
/// коварный класс сбоев: оператор видит устаревший баланс и принимает по нему
/// решение о выдаче. Уникальное имя на каждую подписку полностью исключает
/// гонку — каждый StreamController владеет собственным каналом.
///
/// Использование:
/// ```dart
/// _client.channel(uniqueChannelName('account_balances_all'))
/// ```
int _channelSeq = 0;

/// Возвращает имя канала [base] с монотонным уникальным суффиксом.
String uniqueChannelName(String base) =>
    '${base}_${DateTime.now().microsecondsSinceEpoch}_${_channelSeq++}';
